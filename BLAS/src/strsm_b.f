      SUBROUTINE STRSM_B(SIDE, UPLO, TRANSA, DIAG, M, N,
     +                   ALPHA, ALPHAB, A, AB, LDA, B, BB, LDB)
C
C Reverse-mode (adjoint) derivative of STRSM via the Giles/black-box
C method: differentiates op(A)*X = alpha*B directly, using only the
C original, undifferentiated STRSM -- never the substitution algorithm.
C
C CONVENTION (matches Tapenade's own generated strsm_b.f):
C   B          : untouched, original forward-call input.
C   BB         : IN = seed adjoint dF/dX; OUT = adjoint dF/dB (in place).
C   ALPHAB, AB : OUTPUT ONLY -- zeroed and filled here, not accumulated
C                into whatever the caller passed in.
C
      IMPLICIT NONE
      CHARACTER SIDE, UPLO, TRANSA, DIAG
      INTEGER M, N, LDA, LDB
      REAL ALPHA, ALPHAB
      REAL A(LDA,*), AB(LDA,*)
      REAL B(LDB,*), BB(LDB,*)

      REAL X(M,N)
      CHARACTER TRANSA_T
      LOGICAL LEFT, UPPER, UNIT, NOTRANS
      INTEGER I, J, K

      LEFT    = (SIDE.EQ.'L'   .OR. SIDE.EQ.'l')
      UPPER   = (UPLO.EQ.'U'   .OR. UPLO.EQ.'u')
      UNIT    = (DIAG.EQ.'U'   .OR. DIAG.EQ.'u')
      NOTRANS = (TRANSA.EQ.'N' .OR. TRANSA.EQ.'n')
      IF (NOTRANS) THEN
         TRANSA_T = 'T'
      ELSE
         TRANSA_T = 'N'
      END IF

      IF (M.EQ.0 .OR. N.EQ.0) THEN
         ALPHAB = 0.0E0
         RETURN
      END IF

C     Step 1: Yb solves op(A)^T*Yb = Xb (SIDE='L') or Yb*op(A)^T = Xb (SIDE='R')
C             Overwrites BB in place: held the seed on entry, holds Yb after.
      CALL STRSM(SIDE, UPLO, TRANSA_T, DIAG, M, N, 1.0E0, A, LDA, BB, LDB)

C     Step 2: recompute X from the ORIGINAL, untouched B
      DO J = 1, N
         DO I = 1, M
            X(I,J) = B(I,J)
         END DO
      END DO
      CALL STRSM(SIDE, UPLO, TRANSA, DIAG, M, N, ALPHA, A, LDA, X, M)

C     Step 3: alphab = <Yb, B> (ORIGINAL B, not X)
      ALPHAB = 0.0E0
      DO J = 1, N
         DO I = 1, M
            ALPHAB = ALPHAB + BB(I,J)*B(I,J)
         END DO
      END DO

C     Step 4: Ab, restricted to the triangle STRSM actually reads
      DO J = 1, LDA
         DO I = 1, LDA
            AB(I,J) = 0.0E0
         END DO
      END DO

      IF (LEFT) THEN
         DO J = 1, M
            DO I = 1, M
               IF ((UPPER.AND.I.LE.J) .OR. (.NOT.UPPER.AND.I.GE.J)) THEN
                  IF (.NOT.(UNIT.AND.I.EQ.J)) THEN
                     IF (NOTRANS) THEN
                        DO K = 1, N
                           AB(I,J) = AB(I,J) - BB(I,K)*X(J,K)
                        END DO
                     ELSE
                        DO K = 1, N
                           AB(I,J) = AB(I,J) - X(I,K)*BB(J,K)
                        END DO
                     END IF
                  END IF
               END IF
            END DO
         END DO
      ELSE
         DO J = 1, N
            DO I = 1, N
               IF ((UPPER.AND.I.LE.J) .OR. (.NOT.UPPER.AND.I.GE.J)) THEN
                  IF (.NOT.(UNIT.AND.I.EQ.J)) THEN
                     IF (NOTRANS) THEN
                        DO K = 1, M
                           AB(I,J) = AB(I,J) - X(K,I)*BB(K,J)
                        END DO
                     ELSE
                        DO K = 1, M
                           AB(I,J) = AB(I,J) - BB(K,I)*X(K,J)
                        END DO
                     END IF
                  END IF
               END IF
            END DO
         END DO
      END IF

C     Step 5: Bb = alpha * Yb (BB currently holds Yb from Step 1)
      DO J = 1, N
         DO I = 1, M
            BB(I,J) = ALPHA*BB(I,J)
         END DO
      END DO

      RETURN
      END SUBROUTINE STRSM_B

