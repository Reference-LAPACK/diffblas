      SUBROUTINE DTRSM_BV(SIDE, UPLO, TRANSA, DIAG, M, N,
     +                    ALPHA, ALPHAB, A, AB, LDA, B, BB, LDB, NBDIRS)
C
C Vector reverse-mode (adjoint) derivative of DTRSM, black-box/Giles-style.
C Self-contained -- does not call DTRSM_B. AB/BB store direction as the
C FASTEST-varying index (nbdirs, LDA/LDB, *): gather each direction into
C a plain work array before use, scatter the result back after.
C
C CONVENTION (matches Tapenade's dtrsm_bv.f):
C   B          : untouched, original forward-call input.
C   BB         : IN = seed adjoints (one per direction); OUT = dF/dB.
C   ALPHAB, AB : OUTPUT ONLY, zeroed and filled here per direction.
C
      IMPLICIT NONE
      CHARACTER SIDE, UPLO, TRANSA, DIAG
      INTEGER M, N, LDA, LDB, NBDIRS
      DOUBLE PRECISION ALPHA
      DOUBLE PRECISION ALPHAB(NBDIRS)
      DOUBLE PRECISION A(LDA,*), AB(NBDIRS,LDA,*)
      DOUBLE PRECISION B(LDB,*), BB(NBDIRS,LDB,*)

      DOUBLE PRECISION X(M,N)
      DOUBLE PRECISION BB_SLICE(LDB,N), AB_SLICE(LDA,LDA)
      CHARACTER TRANSA_T
      LOGICAL LEFT, UPPER, UNIT, NOTRANS
      INTEGER ND, I, J, K

      LEFT    = (SIDE.EQ.'L'   .OR. SIDE.EQ.'l')
      UPPER   = (UPLO.EQ.'U'   .OR. UPLO.EQ.'u')
      UNIT    = (DIAG.EQ.'U'   .OR. DIAG.EQ.'u')
      NOTRANS = (TRANSA.EQ.'N' .OR. TRANSA.EQ.'n')
      IF (NOTRANS) THEN
         TRANSA_T = 'T'
      ELSE
         TRANSA_T = 'N'
      END IF

      IF (M.EQ.0 .OR. N.EQ.0) THEN
         DO ND = 1, NBDIRS
            ALPHAB(ND) = 0.0D0
         END DO
         RETURN
      END IF

C     X = solution of the original forward call (same for every direction)
      DO J = 1, N
         DO I = 1, M
            X(I,J) = B(I,J)
         END DO
      END DO
      CALL DTRSM(SIDE, UPLO, TRANSA, DIAG, M, N, ALPHA, A, LDA, X, M)

      DO ND = 1, NBDIRS

C        Gather this direction's seed out of the interleaved BB layout
         DO J = 1, N
            DO I = 1, M
               BB_SLICE(I,J) = BB(ND,I,J)
            END DO
         END DO

C        Step 1: Yb solves op(A)^T*Yb = Xb (overwrites BB_SLICE in place)
         CALL DTRSM(SIDE, UPLO, TRANSA_T, DIAG, M, N, 1.0D0,
     +              A, LDA, BB_SLICE, LDB)

C        Step 2: alphab(nd) = <Yb, B>  (ORIGINAL B, not X)
         ALPHAB(ND) = 0.0D0
         DO J = 1, N
            DO I = 1, M
               ALPHAB(ND) = ALPHAB(ND) + BB_SLICE(I,J)*B(I,J)
            END DO
         END DO

C        Step 3: Ab for this direction, restricted to the triangle read
         DO J = 1, LDA
            DO I = 1, LDA
               AB_SLICE(I,J) = 0.0D0
            END DO
         END DO

         IF (LEFT) THEN
            DO J = 1, M
               DO I = 1, M
                  IF ((UPPER.AND.I.LE.J).OR.
     +                (.NOT.UPPER.AND.I.GE.J)) THEN
                     IF (.NOT.(UNIT.AND.I.EQ.J)) THEN
                        IF (NOTRANS) THEN
                           DO K = 1, N
                              AB_SLICE(I,J) = AB_SLICE(I,J)
     +                                        - BB_SLICE(I,K)*X(J,K)
                           END DO
                        ELSE
                           DO K = 1, N
                              AB_SLICE(I,J) = AB_SLICE(I,J)
     +                                        - X(I,K)*BB_SLICE(J,K)
                           END DO
                        END IF
                     END IF
                  END IF
               END DO
            END DO
         ELSE
            DO J = 1, N
               DO I = 1, N
                  IF ((UPPER.AND.I.LE.J).OR.
     +                (.NOT.UPPER.AND.I.GE.J)) THEN
                     IF (.NOT.(UNIT.AND.I.EQ.J)) THEN
                        IF (NOTRANS) THEN
                           DO K = 1, M
                              AB_SLICE(I,J) = AB_SLICE(I,J)
     +                                        - X(K,I)*BB_SLICE(K,J)
                           END DO
                        ELSE
                           DO K = 1, M
                              AB_SLICE(I,J) = AB_SLICE(I,J)
     +                                        - BB_SLICE(K,I)*X(K,J)
                           END DO
                        END IF
                     END IF
                  END IF
               END DO
            END DO
         END IF

C        Step 4: Bb = alpha * Yb (BB_SLICE currently holds Yb)
         DO J = 1, N
            DO I = 1, M
               BB_SLICE(I,J) = ALPHA*BB_SLICE(I,J)
            END DO
         END DO

C        Scatter this direction's results back into the interleaved layout
         DO J = 1, LDA
            DO I = 1, LDA
               AB(ND,I,J) = AB_SLICE(I,J)
            END DO
         END DO
         DO J = 1, N
            DO I = 1, M
               BB(ND,I,J) = BB_SLICE(I,J)
            END DO
         END DO

      END DO

      RETURN
      END SUBROUTINE DTRSM_BV

