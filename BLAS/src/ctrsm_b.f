      SUBROUTINE CTRSM_B(SIDE, UPLO, TRANSA, DIAG, M, N,
     +                   ALPHA, ALPHAB, A, AB, LDA, B, BB, LDB)
!
! Reverse-mode (adjoint) derivative of CTRSM, black-box/Giles-style,
! Wirtinger/CR-calculus convention. ALPHA complex.
! Bb = CONJG(ALPHA)*Yb -- NOT alpha*Yb (see notes above).
!
      IMPLICIT NONE
      CHARACTER SIDE, UPLO, TRANSA, DIAG
      INTEGER M, N, LDA, LDB
      COMPLEX ALPHA, ALPHAB
      COMPLEX A(LDA,*), AB(LDA,*)
      COMPLEX B(LDB,*), BB(LDB,*)

      COMPLEX X(M,N), BLOC(M,N)
      LOGICAL LEFT, UPPER, UNIT, ISN, IST, ISC
      INTEGER I, J, K
      INTRINSIC CONJG

      LEFT  = (SIDE.EQ.'L'  .OR. SIDE.EQ.'l')
      UPPER = (UPLO.EQ.'U'  .OR. UPLO.EQ.'u')
      UNIT  = (DIAG.EQ.'U'  .OR. DIAG.EQ.'u')
      ISN   = (TRANSA.EQ.'N' .OR. TRANSA.EQ.'n')
      IST   = (TRANSA.EQ.'T' .OR. TRANSA.EQ.'t')
      ISC   = (TRANSA.EQ.'C' .OR. TRANSA.EQ.'c')

      IF (M.EQ.0 .OR. N.EQ.0) THEN
         ALPHAB = (0.0E0,0.0E0)
         RETURN
      END IF

      DO J = 1, N
         DO I = 1, M
            BLOC(I,J) = B(I,J)
         END DO
      END DO

C     Solve M^H*Yb = Xb (SIDE='L') or Yb*M^H = Xb (SIDE='R'), overwrite BB
      IF (ISN) THEN
         CALL CTRSM(SIDE, UPLO, 'C', DIAG, M, N, (1.0E0,0.0E0),
     +              A, LDA, BB, LDB)
      ELSE IF (ISC) THEN
         CALL CTRSM(SIDE, UPLO, 'N', DIAG, M, N, (1.0E0,0.0E0),
     +              A, LDA, BB, LDB)
      ELSE
C        TRANSA='T': conj(A)*Yb=Xb <=> A*conj(Yb)=conj(Xb) (SIDE-agnostic trick)
         DO J = 1, N
            DO I = 1, M
               BB(I,J) = CONJG(BB(I,J))
            END DO
         END DO
         CALL CTRSM(SIDE, UPLO, 'N', DIAG, M, N, (1.0E0,0.0E0),
     +              A, LDA, BB, LDB)
         DO J = 1, N
            DO I = 1, M
               BB(I,J) = CONJG(BB(I,J))
            END DO
         END DO
      END IF

      DO J = 1, N
         DO I = 1, M
            X(I,J) = BLOC(I,J)
         END DO
      END DO
      CALL CTRSM(SIDE, UPLO, TRANSA, DIAG, M, N, ALPHA, A, LDA, X, M)

C     alphab = sum Yb .* conj(B)  (ORIGINAL B, not X)
      ALPHAB = (0.0E0,0.0E0)
      DO J = 1, N
         DO I = 1, M
            ALPHAB = ALPHAB + BB(I,J)*CONJG(BLOC(I,J))
         END DO
      END DO

      DO J = 1, LDA
         DO I = 1, LDA
            AB(I,J) = (0.0E0,0.0E0)
         END DO
      END DO

      IF (LEFT) THEN
         DO J = 1, M
            DO I = 1, M
               IF ((UPPER.AND.I.LE.J) .OR. (.NOT.UPPER.AND.I.GE.J)) THEN
                  IF (.NOT.(UNIT.AND.I.EQ.J)) THEN
                     IF (ISN) THEN
                        DO K = 1, N
                           AB(I,J) = AB(I,J) - BB(I,K)*CONJG(X(J,K))
                        END DO
                     ELSE IF (IST) THEN
                        DO K = 1, N
                           AB(I,J) = AB(I,J) - CONJG(X(I,K))*BB(J,K)
                        END DO
                     ELSE
                        DO K = 1, N
                           AB(I,J) = AB(I,J) - CONJG(BB(J,K))*X(I,K)
                        END DO
                     END IF
                  END IF
               END IF
            END DO
         END DO
      ELSE
         DO J = 1, N
            DO I = 1, N
               IF ((UPPER.AND.I.LE.J) .OR. (.NOT.UPPER.AND.I.GE.J)) THEN
                  IF (.NOT.(UNIT.AND.I.EQ.J)) THEN
                     IF (ISN) THEN
                        DO K = 1, M
                           AB(I,J) = AB(I,J) - CONJG(X(K,I))*BB(K,J)
                        END DO
                     ELSE IF (IST) THEN
                        DO K = 1, M
                           AB(I,J) = AB(I,J) - CONJG(X(K,J))*BB(K,I)
                        END DO
                     ELSE
                        DO K = 1, M
                           AB(I,J) = AB(I,J) - X(K,J)*CONJG(BB(K,I))
                        END DO
                     END IF
                  END IF
               END IF
            END DO
         END DO
      END IF

C     Bb = CONJG(alpha) * Yb  (BB currently holds Yb)
      DO J = 1, N
         DO I = 1, M
            BB(I,J) = CONJG(ALPHA)*BB(I,J)
         END DO
      END DO

      RETURN
      END SUBROUTINE CTRSM_B

