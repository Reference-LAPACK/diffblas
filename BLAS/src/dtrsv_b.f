      END DO

C     Yb solves op(A)^T*Yb = Xb
      CALL DTRSV(UPLO, TRANS_T, DIAG, N, A, LDA, YB, 1)

C     Recompute S from the original, untouched B
      DO I = 1, N
         S(I) = BLOC(I)
      END DO
      CALL DTRSV(UPLO, TRANS, DIAG, N, A, LDA, S, 1)

      DO J = 1, LDA
         DO I = 1, LDA
            AB(I,J) = 0.0D0
         END DO
      END DO

      DO J = 1, N
         DO I = 1, N
            IF ((UPPER.AND.I.LE.J) .OR. (.NOT.UPPER.AND.I.GE.J)) THEN
               IF (.NOT.(UNIT.AND.I.EQ.J)) THEN
                  IF (NOTRANS) THEN
                     AB(I,J) = -YB(I)*S(J)
                  ELSE
                     AB(I,J) = -S(I)*YB(J)
                  END IF
               END IF
            END IF
         END DO
      END DO

C     Bb = Yb (no alpha in TRSV)
      DO I = 1, N
         XB(KX + (I-1)*INCX) = YB(I)
      END DO

      RETURN
      END SUBROUTINE DTRSV_B

