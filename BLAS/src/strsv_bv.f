                     IF (NOTRANS) THEN
                        AB_SLICE(I,J) = -YB(I)*S(J)
                     ELSE
                        AB_SLICE(I,J) = -S(I)*YB(J)
                     END IF
                  END IF
               END IF
            END DO
         END DO

         DO I = 1, N
            XB(ND, KX + (I-1)*INCX) = YB(I)
         END DO
         DO J = 1, LDA
            DO I = 1, LDA
               AB(ND,I,J) = AB_SLICE(I,J)
            END DO
         END DO

      END DO

      RETURN
