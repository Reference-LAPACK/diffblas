                  ELSE IF (IST) THEN
                     AB(I,J) = -YB(J)*DCONJG(S(I))
                  ELSE
                     AB(I,J) = -DCONJG(YB(J))*S(I)
                  END IF
               END IF
            END IF
         END DO
      END DO

      DO I = 1, N
         XB(KX + (I-1)*INCX) = YB(I)
      END DO

      RETURN
