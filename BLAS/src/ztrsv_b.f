         YB(I)   = XB(KX + (I-1)*INCX)
      END DO

      IF (ISN) THEN
         CALL ZTRSV(UPLO, 'C', DIAG, N, A, LDA, YB, 1)
      ELSE IF (ISC) THEN
         CALL ZTRSV(UPLO, 'N', DIAG, N, A, LDA, YB, 1)
      ELSE
