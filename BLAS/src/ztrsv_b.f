            YB(I) = DCONJG(YB(I))
         END DO
         CALL ZTRSV(UPLO, 'N', DIAG, N, A, LDA, YB, 1)
         DO I = 1, N
            YB(I) = DCONJG(YB(I))
         END DO
      END IF

