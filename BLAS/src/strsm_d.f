      SUBROUTINE STRSM_D(SIDE, UPLO, TRANSA, DIAG, M, N,
     +                   ALPHA, ALPHAD, A, AD, LDA, B, BD, LDB)
!
! Forward-mode derivative of STRSM via the black-box / Giles-style
! approach: differentiate op(A)*X = alpha*B directly. Uses only the
! original STRSM and STRMM.
!
      IMPLICIT NONE
      CHARACTER SIDE, UPLO, TRANSA, DIAG
      INTEGER M, N, LDA, LDB
      REAL ALPHA, ALPHAD
      REAL A(LDA,*), AD(LDA,*)
      REAL B(LDB,*), BD(LDB,*)

      REAL X(M,N), T(M,N)
      INTEGER I, J

      IF (M.EQ.0 .OR. N.EQ.0) RETURN

C     Step 1: X = solution of the original forward call
      DO J = 1, N
         DO I = 1, M
            X(I,J) = B(I,J)
         END DO
      END DO
      CALL STRSM(SIDE, UPLO, TRANSA, DIAG, M, N, ALPHA, A, LDA, X, M)

C     Step 2: T = op(Ad)*X (SIDE='L') or X*op(Ad) (SIDE='R')
      DO J = 1, N
         DO I = 1, M
            T(I,J) = X(I,J)
         END DO
      END DO
      CALL STRMM(SIDE, UPLO, TRANSA, DIAG, M, N, 1.0E0, AD, LDA, T, M)

C     Step 3: RHS = alphad*B + alpha*Bd - T, built in place in BD
      DO J = 1, N
         DO I = 1, M
            BD(I,J) = ALPHAD*B(I,J) + ALPHA*BD(I,J) - T(I,J)
         END DO
      END DO

C     Step 4: solve the SAME triangular system again -> dX, overwrites BD
      CALL STRSM(SIDE, UPLO, TRANSA, DIAG, M, N, 1.0E0, A, LDA, BD, LDB)

      RETURN
      END SUBROUTINE STRSM_D

