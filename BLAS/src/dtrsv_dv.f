      SUBROUTINE DTRSV_DV(UPLO, TRANS, DIAG, N, A, AD, LDA, X, XD,
     +                    INCX, NBDIRS)
!
! Vector forward-mode derivative of DTRSV, black-box/Giles-style.
! Self-contained -- does not call DTRSV_D.
!
      IMPLICIT NONE
      INCLUDE 'DIFFSIZES.inc'
      CHARACTER UPLO, TRANS, DIAG
      INTEGER N, LDA, INCX, NBDIRS
      DOUBLE PRECISION A(LDA,*), AD(NBDIRSMAX,LDA,*)
      DOUBLE PRECISION X(*), XD(NBDIRSMAX,*)

      DOUBLE PRECISION S(N), T(N), W(N), AD_SLICE(LDA,LDA)
      INTEGER ND, I, J, KX

      IF (NBDIRS.LE.0 .OR. NBDIRS.GT.NBDIRSMAX) THEN
         WRITE(*,'(A,I0,A,I0,A)') 'Error: nbdirs=', NBDIRS,
     +      ' must be in 1..nbdirsmax=', NBDIRSMAX, '. Stopping.'
         STOP 1
      END IF

      IF (N.EQ.0) RETURN

      IF (INCX.GE.1) THEN
         KX = 1
      ELSE
         KX = 1 - (N-1)*INCX
      END IF

C     S = solution, overwriting X in place (same for every direction)
      CALL DTRSV(UPLO, TRANS, DIAG, N, A, LDA, X, INCX)
      DO I = 1, N
         S(I) = X(KX + (I-1)*INCX)
      END DO

      DO ND = 1, NBDIRS

         DO J = 1, N
            DO I = 1, N
               AD_SLICE(I,J) = AD(ND,I,J)
            END DO
         END DO

C        T = op(Ad)*S (local copy, S stays untouched)
         DO I = 1, N
            T(I) = S(I)
         END DO
         CALL DTRMV(UPLO, TRANS, DIAG, N, AD_SLICE, LDA, T, 1)

C        RHS = Xd_in - T, gathered respecting INCX
         DO I = 1, N
            W(I) = XD(ND, KX + (I-1)*INCX) - T(I)
         END DO

         CALL DTRSV(UPLO, TRANS, DIAG, N, A, LDA, W, 1)

         DO I = 1, N
            XD(ND, KX + (I-1)*INCX) = W(I)
         END DO

      END DO

      RETURN
      END SUBROUTINE DTRSV_DV

