      SUBROUTINE CTRSV_D(UPLO, TRANS, DIAG, N, A, AD, LDA, X, XD, INCX)
!
! Forward-mode derivative of CTRSV, black-box/Giles-style. Passing the
! SAME trans flag to CTRMV/CTRSV as the primal call automatically
! applies the correct conjugation for TRANS='C' -- no manual CONJG needed.
!
      IMPLICIT NONE
      CHARACTER UPLO, TRANS, DIAG
      INTEGER N, LDA, INCX
      COMPLEX A(LDA,*), AD(LDA,*)
      COMPLEX X(*), XD(*)

      COMPLEX S(N), W(N)
      INTEGER I, KX

      IF (N.EQ.0) RETURN

      IF (INCX.GE.1) THEN
         KX = 1
      ELSE
         KX = 1 - (N-1)*INCX
      END IF

      CALL CTRSV(UPLO, TRANS, DIAG, N, A, LDA, X, INCX)
      DO I = 1, N
         S(I) = X(KX + (I-1)*INCX)
      END DO

      DO I = 1, N
         W(I) = S(I)
      END DO
      CALL CTRMV(UPLO, TRANS, DIAG, N, AD, LDA, W, 1)

      DO I = 1, N
         W(I) = XD(KX + (I-1)*INCX) - W(I)
      END DO

      CALL CTRSV(UPLO, TRANS, DIAG, N, A, LDA, W, 1)

      DO I = 1, N
         XD(KX + (I-1)*INCX) = W(I)
      END DO

      RETURN
      END SUBROUTINE CTRSV_D

